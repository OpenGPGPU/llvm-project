#ifndef LLVM_LIB_TARGET_OPENGPU_OPENGPUSUBTARGET_H
#define LLVM_LIB_TARGET_OPENGPU_OPENGPUSUBTARGET_H

#include "OpenGPUFrameLowering.h"
#include "OpenGPUISelLowering.h"
#include "OpenGPUInstrInfo.h"
#include "OpenGPUSelectionDAGInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include "llvm/IR/DataLayout.h"
#include "llvm/Target/TargetMachine.h"

#define GET_SUBTARGETINFO_HEADER
#include "OpenGPUGenSubtargetInfo.inc"

namespace llvm {

class OpenGPUSubtarget : public OpenGPUGenSubtargetInfo {
public:
  // This constructor initializes the data members to match that
  // of the specified triple.
  OpenGPUSubtarget(const Triple &TargetTriple, StringRef Cpu,
                 StringRef FeatureString, const TargetMachine &TM,
                 const TargetOptions &Options, CodeModel::Model CodeModel,
                 CodeGenOptLevel OptLevel);

  // ParseSubtargetFeatures - Parses features string setting specified
  // subtarget options.  Definition of function is auto generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  OpenGPUSubtarget &initializeSubtargetDependencies(StringRef CPU, StringRef FS);

  void initSubtargetFeatures(StringRef CPU, StringRef FS);

  bool enableMachineScheduler() const override { return true; }

  const OpenGPUInstrInfo *getInstrInfo() const override { return &InstrInfo; }

  const TargetFrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }

  const OpenGPURegisterInfo *getRegisterInfo() const override {
    return &InstrInfo.getRegisterInfo();
  }

  const OpenGPUTargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }

  const OpenGPUSelectionDAGInfo *getSelectionDAGInfo() const override {
    return &TSInfo;
  }

private:
  OpenGPUInstrInfo InstrInfo;
  OpenGPUFrameLowering FrameLowering;
  OpenGPUTargetLowering TLInfo;
  OpenGPUSelectionDAGInfo TSInfo;
};
} // namespace llvm

#endif // LLVM_LIB_TARGET_OPENGPU_OPENGPUSUBTARGET_H
